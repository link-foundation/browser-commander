#!/usr/bin/env node
/**
 * Generate the typed Rust Playwright protocol client from the official spec.
 *
 * Issue #108 asks for the Rust Playwright API to talk to the official
 * Playwright driver (`playwright run-driver`) with typed bindings generated
 * from Playwright's protocol definition, not a hand-written subset. The spec is
 * vendored verbatim under `rust/protocol/playwright/` (Apache-2.0, see the
 * README there) and this script turns every interface, command, event,
 * initializer, struct, mixin and enum in it into Rust:
 *
 * - each object/mixin becomes a serde struct, each enum a serde enum;
 * - each interface `X` becomes a channel type `X` with one `async fn` per
 *   command (`XGotoParams` -> `XGotoResult`), an `XInitializer` struct and an
 *   `XEvent` enum with one variant per event;
 * - references to other interfaces are typed `Ref<Interface>` values that the
 *   connection resolves to the channel object the driver created.
 *
 * The output goes to `rust/src/playwright/protocol/`. Files are packed below
 * the repository's 1500-line limit. `--check` regenerates in memory and fails
 * on any drift, which is what the JavaScript coverage test and CI run.
 *
 * Usage:
 *   node scripts/generate-playwright-protocol.mjs          # rewrite the files
 *   node scripts/generate-playwright-protocol.mjs --check  # fail on drift
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_DIR = path.join(ROOT, 'rust', 'protocol', 'playwright');
const OUT_DIR = path.join(ROOT, 'rust', 'src', 'playwright', 'protocol');
const MAX_FILE_LINES = 1200;
const HEADER = [
  '// @generated by scripts/generate-playwright-protocol.mjs from',
  '// rust/protocol/playwright/*.yml. Do not edit by hand.',
];
const RUST_KEYWORDS = new Set(
  (
    'as async await break const continue crate dyn else enum extern false fn ' +
    'for if impl in let loop match mod move mut pub ref return self static ' +
    'struct super trait true type unsafe use where while abstract become box ' +
    'do final macro override priv typeof unsized virtual yield try gen'
  ).split(' '),
);
const PRIMITIVES = {
  string: 'String',
  int: 'i64',
  float: 'f64',
  boolean: 'bool',
  binary: 'Binary',
  json: 'serde_json::Value',
  Channel: 'ObjectRef',
};
const DERIVE =
  '#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]';

/** Load and merge every spec file; keys are unique across files. */
export function loadSpec(specDir = SPEC_DIR) {
  const require = createRequire(path.join(ROOT, 'js', 'package.json'));
  const YAML = require('yaml');
  const definitions = {};
  const files = readdirSync(specDir)
    .filter((file) => file.endsWith('.yml'))
    .sort();
  for (const file of files) {
    const parsed = YAML.parse(readFileSync(path.join(specDir, file), 'utf8'));
    for (const [name, definition] of Object.entries(parsed ?? {})) {
      if (definitions[name]) {
        throw new Error(`${name} is defined twice (second time in ${file})`);
      }
      definitions[name] = { ...definition, file };
    }
  }
  return definitions;
}

function words(name) {
  return String(name)
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}

export function pascalCase(name) {
  return words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join('');
}

export function snakeCase(name) {
  return words(name)
    .map((word) => word.toLowerCase())
    .join('_');
}

/** A Rust identifier for a field or method, escaping keywords. */
export function rustIdent(name) {
  let ident = snakeCase(name) || 'value';
  if (/^[0-9]/.test(ident)) {
    ident = `v${ident}`;
  }
  return RUST_KEYWORDS.has(ident) ? `r#${ident}` : ident;
}

function variantName(literal) {
  const text = String(literal);
  if (text === '') {
    return 'Empty';
  }
  const negative = text.startsWith('-');
  let name = pascalCase(negative ? text.slice(1) : text);
  if (negative) {
    name = `Negative${name || 'Value'}`;
  }
  if (!name || /^[0-9]/.test(name)) {
    name = `V${name}`;
  }
  return name;
}

function stripOptional(type) {
  return type.endsWith('?')
    ? { base: type.slice(0, -1), optional: true }
    : { base: type, optional: false };
}

function rustString(text) {
  return JSON.stringify(String(text));
}

class Generator {
  constructor(definitions) {
    this.definitions = definitions;
    this.interfaces = new Set(
      Object.keys(definitions).filter(
        (name) => definitions[name].type === 'interface',
      ),
    );
    // unit name -> array of item blocks (arrays of lines)
    this.units = new Map();
    this.currentUnit = null;
    this.emittedNames = new Set();
    this.structStack = [];
  }

  emit(name, lines) {
    if (this.emittedNames.has(name)) {
      throw new Error(`Generated type ${name} would be emitted twice (first: ${this.firstUnit.get(name)}, now: ${this.currentUnit})`);
    }
    this.emittedNames.add(name);
    (this.firstUnit ??= new Map()).set(name, this.currentUnit);
    this.units.get(this.currentUnit).push(lines);
  }

  inUnit(unit, callback) {
    const previous = this.currentUnit;
    if (!this.units.has(unit)) {
      this.units.set(unit, []);
    }
    this.currentUnit = unit;
    callback();
    this.currentUnit = previous;
  }

  /** Resolve a spec type to a Rust type, emitting inline types as needed. */
  resolve(spec, hint) {
    if (typeof spec === 'string') {
      const { base, optional } = stripOptional(spec);
      let rust;
      if (PRIMITIVES[base]) {
        rust = PRIMITIVES[base];
      } else if (this.interfaces.has(base)) {
        rust = `Ref<${base}>`;
      } else if (this.definitions[base]) {
        // A struct that contains itself (AndroidSelector.hasChild.selector)
        // needs indirection to have a size.
        rust = this.structStack.includes(base) ? `Box<${base}>` : base;
      } else {
        throw new Error(`Unknown protocol type ${base} (at ${hint})`);
      }
      return { rust, optional };
    }
    if (!spec || typeof spec.type !== 'string') {
      throw new Error(`Unsupported type definition at ${hint}`);
    }
    const { base, optional } = stripOptional(spec.type);
    if (base === 'object') {
      this.emitStruct(hint, spec.properties ?? {}, []);
      return { rust: hint, optional };
    }
    if (base === 'array') {
      // A Vec already gives indirection, so nothing inside needs boxing.
      const outer = this.structStack;
      this.structStack = [];
      const item = this.resolve(spec.items, hint);
      this.structStack = outer;
      const itemType = item.optional ? `Option<${item.rust}>` : item.rust;
      return { rust: `Vec<${itemType}>`, optional };
    }
    if (base === 'enum') {
      this.emitEnum(hint, spec.literals ?? [], []);
      return { rust: hint, optional };
    }
    throw new Error(`Unsupported composite type ${spec.type} at ${hint}`);
  }

  emitStruct(name, properties, docs) {
    this.structStack.push(name);
    const fields = [];
    const used = new Set();
    for (const [key, type] of Object.entries(properties ?? {})) {
      if (key.startsWith('$mixin')) {
        const mixin = this.definitions[type];
        if (!mixin || mixin.type !== 'mixin') {
          throw new Error(`${name}.${key} names unknown mixin ${type}`);
        }
        let ident = rustIdent(type);
        while (used.has(ident)) ident = `${ident}_mixin`;
        used.add(ident);
        fields.push(
          `    /// Properties of the \`${type}\` mixin.`,
          '    #[serde(flatten)]',
          `    pub ${ident}: ${type},`,
        );
        continue;
      }
      const resolved = this.resolve(type, `${name}${pascalCase(key)}`);
      let ident = rustIdent(key);
      while (used.has(ident)) ident = `${ident}_`;
      used.add(ident);
      fields.push(`    #[serde(rename = ${rustString(key)}`);
      if (resolved.optional) {
        fields[fields.length - 1] +=
          ', default, skip_serializing_if = "Option::is_none")]';
        fields.push(`    pub ${ident}: Option<${resolved.rust}>,`);
      } else {
        fields[fields.length - 1] += ')]';
        fields.push(`    pub ${ident}: ${resolved.rust},`);
      }
    }
    this.structStack.pop();
    this.emit(name, [
      ...docs,
      DERIVE,
      fields.length ? `pub struct ${name} {` : `pub struct ${name} {}`,
      ...(fields.length ? [...fields, '}'] : []),
    ]);
  }

  emitEnum(name, literals, docs) {
    const used = new Set();
    const variants = [];
    literals.forEach((literal, index) => {
      let variant = variantName(literal);
      while (used.has(variant)) variant = `${variant}V`;
      used.add(variant);
      if (index === 0) variants.push('    #[default]');
      variants.push(`    #[serde(rename = ${rustString(literal)})]`);
      variants.push(`    ${variant},`);
    });
    this.emit(name, [
      ...docs,
      '#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]',
      `pub enum ${name} {`,
      ...variants,
      '}',
    ]);
  }

  /** Commands and events of an interface including inherited ones. */
  members(name, kind) {
    const definition = this.definitions[name];
    const inherited = definition.extends
      ? this.members(definition.extends, kind)
      : [];
    const own = Object.entries(definition[kind] ?? {}).map(([member, spec]) => ({
      owner: name,
      name: member,
      spec: spec ?? {},
    }));
    const ownNames = new Set(own.map((member) => member.name));
    return [
      ...inherited.filter((member) => !ownNames.has(member.name)),
      ...own,
    ];
  }

  hasEntries(object) {
    return Object.keys(object ?? {}).length > 0;
  }

  emitInterface(name) {
    const definition = this.definitions[name];
    const file = definition.file;
    this.emitStruct(`${name}Initializer`, definition.initializer ?? {}, [
      `/// Initializer the driver sends when it creates a \`${name}\`.`,
    ]);
    for (const [command, spec] of Object.entries(definition.commands ?? {})) {
      const base = `${name}${pascalCase(command)}`;
      const title = spec?.title ? ` (${spec.title})` : '';
      if (this.hasEntries(spec?.parameters)) {
        this.emitStruct(`${base}Params`, spec.parameters, [
          `/// Parameters of \`${name}.${command}\`${title}.`,
        ]);
      }
      if (this.hasEntries(spec?.returns)) {
        this.emitStruct(`${base}Result`, spec.returns, [
          `/// Result of \`${name}.${command}\`${title}.`,
        ]);
      }
    }
    for (const [event, spec] of Object.entries(definition.events ?? {})) {
      if (this.hasEntries(spec?.parameters)) {
        this.emitStruct(`${name}${pascalCase(event)}EventParams`, spec.parameters, [
          `/// Payload of the \`${name}.${event}\` event.`,
        ]);
      }
    }

    const events = this.members(name, 'events');
    const eventLines = [
      `/// Events a \`${name}\` channel can emit.`,
      '#[derive(Debug, Clone, PartialEq)]',
      `pub enum ${name}Event {`,
    ];
    const parseArms = [];
    for (const event of events) {
      const variant = pascalCase(event.name);
      const payload = `${event.owner}${variant}EventParams`;
      eventLines.push(`    /// \`${event.owner}.${event.name}\``);
      if (this.hasEntries(event.spec.parameters)) {
        eventLines.push(`    ${variant}(${payload}),`);
        parseArms.push(
          `            ${rustString(event.name)} => Ok(Self::${variant}(serde_json::from_value(params)?)),`,
        );
      } else {
        eventLines.push(`    ${variant},`);
        parseArms.push(
          `            ${rustString(event.name)} => Ok(Self::${variant}),`,
        );
      }
    }
    eventLines.push(
      '    /// An event this binding does not know (a newer driver).',
      '    Unknown {',
      '        /// Event name.',
      '        method: String,',
      '        /// Raw event parameters.',
      '        params: serde_json::Value,',
      '    },',
      '}',
      '',
      `impl ProtocolEvent for ${name}Event {`,
      '    fn parse(method: &str, params: serde_json::Value) -> Result<Self, serde_json::Error> {',
      '        match method {',
      ...parseArms,
      '            _ => Ok(Self::Unknown { method: method.to_string(), params }),',
      '        }',
      '    }',
      '}',
    );
    this.emit(`${name}Event`, eventLines);

    const subtypes = Object.keys(this.definitions).filter((other) =>
      this.isSubtype(other, name),
    );
    const methods = [];
    for (const command of this.members(name, 'commands')) {
      const base = `${command.owner}${pascalCase(command.name)}`;
      const ident = rustIdent(command.name);
      const hasParams = this.hasEntries(command.spec.parameters);
      const hasResult = this.hasEntries(command.spec.returns);
      const result = hasResult ? `${base}Result` : '()';
      const flags = [
        command.spec.internal ? 'internal' : null,
        command.spec.title ? `"${command.spec.title}"` : null,
      ].filter(Boolean);
      methods.push(
        '',
        `    /// \`${command.owner}.${command.name}\`${flags.length ? ` (${flags.join(', ')})` : ''}.`,
        `    pub async fn ${ident}(&self${hasParams ? `, params: ${base}Params` : ''}) -> Result<${result}, ProtocolError> {`,
      );
      const params = hasParams ? '&params' : '&serde_json::json!({})';
      methods.push(
        hasResult
          ? `        self.channel.send(${rustString(command.name)}, ${params}).await`
          : `        self.channel.send_no_result(${rustString(command.name)}, ${params}).await`,
        '    }',
      );
    }
    this.emit(name, [
      `/// Channel for the \`${name}\` interface (\`${file}\`).`,
      '#[derive(Debug, Clone)]',
      `pub struct ${name} {`,
      '    channel: Channel,',
      '}',
      '',
      `impl ChannelType for ${name} {`,
      `    const INTERFACE: &'static str = ${rustString(name)};`,
      `    type Initializer = ${name}Initializer;`,
      `    type Event = ${name}Event;`,
      '',
      '    fn accepts(interface: &str) -> bool {',
      `        matches!(interface, ${subtypes.map(rustString).join(' | ')})`,
      '    }',
      '',
      '    fn from_channel(channel: Channel) -> Self {',
      '        Self { channel }',
      '    }',
      '',
      '    fn channel(&self) -> &Channel {',
      '        &self.channel',
      '    }',
      '}',
      '',
      `impl ${name} {`,
      ...methods.slice(1),
      '}',
    ]);
  }

  isSubtype(candidate, ancestor) {
    let current = candidate;
    while (current) {
      if (current === ancestor) return true;
      current = this.definitions[current]?.extends;
    }
    return false;
  }

  generate() {
    for (const [name, definition] of Object.entries(this.definitions)) {
      const unit =
        definition.type === 'interface'
          ? snakeCase(name)
          : `${snakeCase(definition.file.replace(/\.yml$/, ''))}_types`;
      this.inUnit(unit, () => {
        if (definition.type === 'interface') {
          this.emitInterface(name);
        } else if (definition.type === 'enum') {
          this.emitEnum(name, definition.literals ?? [], [
            `/// \`${name}\` enum from \`${definition.file}\`.`,
          ]);
        } else if (definition.type === 'object' || definition.type === 'mixin') {
          this.emitStruct(name, definition.properties ?? {}, [
            `/// \`${name}\` ${definition.type} from \`${definition.file}\`.`,
          ]);
        } else {
          throw new Error(`Unsupported definition kind ${definition.type}`);
        }
      });
    }
    return this.pack();
  }

  pack() {
    const files = new Map();
    const modules = [];
    const preamble = [
      ...HEADER,
      '',
      '#![allow(clippy::all, missing_docs, unused_imports)]',
      '',
      'use serde::{Deserialize, Serialize};',
      '',
      'use super::*;',
      'use crate::playwright::connection::{',
      '    Binary, Channel, ChannelType, ObjectRef, ProtocolError, ProtocolEvent, Ref,',
      '};',
      '',
    ];
    for (const unit of [...this.units.keys()].sort()) {
      const items = this.units.get(unit);
      let part = 1;
      let current = [];
      const flush = () => {
        if (!current.length) return;
        const module = part === 1 ? unit : `${unit}_${part}`;
        modules.push(module);
        files.set(`${module}.rs`, [...preamble, ...current].join('\n') + '\n');
        part += 1;
        current = [];
      };
      for (const item of items) {
        const projected = preamble.length + current.length + item.length + 1;
        if (current.length && projected > MAX_FILE_LINES) flush();
        current.push(...item, '');
      }
      if (current.length) current.pop();
      flush();
    }
    const commandCount = Object.values(this.definitions).reduce(
      (total, definition) =>
        total + Object.keys(definition.commands ?? {}).length,
      0,
    );
    files.set(
      'mod.rs',
      [
        ...HEADER,
        '',
        '//! Typed Playwright protocol bindings generated from the vendored spec.',
        '//!',
        `//! ${this.interfaces.size} interfaces and ${commandCount} commands. Every interface is a`,
        '//! channel type with one `async fn` per command; see',
        '//! [`crate::playwright::connection`] for the runtime they run on.',
        '',
        '/// Playwright release the vendored protocol spec was taken from.',
        `pub const PROTOCOL_VERSION: &str = ${rustString(this.version)};`,
        '',
        ...modules.map((module) => `mod ${module};`),
        '',
        ...modules.map((module) => `pub use ${module}::*;`),
        '',
      ].join('\n'),
    );
    return files;
  }
}

/** Generate the protocol module files as a Map of file name -> contents. */
export function generateProtocol(
  definitions = loadSpec(),
  version = readFileSync(path.join(SPEC_DIR, 'VERSION'), 'utf8').trim(),
) {
  const generator = new Generator(definitions);
  generator.version = version;
  return generator.generate();
}

function main(argv) {
  const check = argv.includes('--check');
  const files = generateProtocol();
  const existing = existsSync(OUT_DIR)
    ? readdirSync(OUT_DIR).filter((file) => file.endsWith('.rs'))
    : [];
  if (check) {
    const problems = [];
    for (const [file, contents] of files) {
      const target = path.join(OUT_DIR, file);
      if (!existsSync(target)) problems.push(`missing ${file}`);
      else if (readFileSync(target, 'utf8') !== contents)
        problems.push(`stale ${file}`);
    }
    for (const file of existing) {
      if (!files.has(file)) problems.push(`unexpected ${file}`);
    }
    if (problems.length) {
      console.error(
        `Playwright protocol bindings are out of date (${problems.join(', ')}).\n` +
          'Run: node scripts/generate-playwright-protocol.mjs',
      );
      process.exit(1);
    }
    console.log(`Playwright protocol bindings are up to date (${files.size} files).`);
    return;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  for (const file of existing) {
    if (!files.has(file)) rmSync(path.join(OUT_DIR, file));
  }
  for (const [file, contents] of files) {
    writeFileSync(path.join(OUT_DIR, file), contents);
  }
  console.log(`Wrote ${files.size} files to ${path.relative(ROOT, OUT_DIR)}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}

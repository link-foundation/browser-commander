#!/usr/bin/env node
/**
 * Copy the parts of trace recording that are not JavaScript-specific into the
 * Python and Rust packages (issue #108).
 *
 * A trace is recorded by running four functions inside the page and rendered
 * by one static viewer. Python and Rust record natively, so they need the
 * same in-page code and the same viewer: a second implementation of either
 * would capture a different page or draw a different trace. This script
 * serializes them out of `js/src/traces/` into one JSON asset per package:
 *
 * - `python/src/browser_commander/traces/assets.json`
 * - `rust/src/traces/assets.json` (embedded with `include_str!`)
 *
 * `--check` regenerates in memory and fails if either copy differs, which is
 * what the JavaScript unit test and CI run.
 *
 * Usage:
 *   node scripts/generate-trace-assets.mjs          # rewrite the assets
 *   node scripts/generate-trace-assets.mjs --check  # fail on any drift
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const TRACE_ASSET_TARGETS = Object.freeze([
  'python/src/browser_commander/traces/assets.json',
  'rust/src/traces/assets.json',
]);

/**
 * A function's source as written, with LF line endings.
 *
 * `Function.prototype.toString()` returns the text of the file, so a Windows
 * checkout with CRLF endings would otherwise produce different assets.
 *
 * @param {Function} fn - The in-page function
 * @returns {string} Its source
 */
const sourceOf = (fn) => fn.toString().replace(/\r\n/gu, '\n');

const traces = (file) =>
  import(pathToFileURL(path.join(ROOT, 'js/src/traces', file)).href);

/**
 * Build the asset document.
 *
 * @returns {Promise<string>} The JSON text every target holds
 */
export async function renderTraceAssets() {
  const capture = await traces('page-capture.js');
  const viewer = await traces('viewer.js');
  const redaction = await traces('redaction.js');
  const video = await import(
    pathToFileURL(path.join(ROOT, 'js/src/capture/video.js')).href
  );
  const document = {
    note: 'Generated by scripts/generate-trace-assets.mjs from js/src/traces; do not edit.',
    recorderGlobal: capture.RECORDER_GLOBAL,
    redacted: redaction.REDACTED,
    capture: {
      captureSnapshot: sourceOf(capture.captureSnapshotInPage),
      installMutationRecorder: sourceOf(capture.installMutationRecorderInPage),
      drainMutations: sourceOf(capture.drainMutationsInPage),
      stopMutationRecorder: sourceOf(capture.stopMutationRecorderInPage),
      encodeVideo: sourceOf(video.encodeVideoInPage),
    },
    viewer: {
      style: viewer.VIEWER_STYLE,
      script: viewer.VIEWER_SCRIPT,
    },
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

/**
 * Compare or rewrite every target.
 *
 * @param {Object} [options] - `{check}`
 * @returns {Promise<string[]>} Targets that differ (check) or were written
 */
export async function generateTraceAssets({ check = false } = {}) {
  const text = await renderTraceAssets();
  const changed = [];
  for (const target of TRACE_ASSET_TARGETS) {
    const file = path.join(ROOT, target);
    let current = null;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // Missing counts as out of date.
    }
    if (current === text) {
      continue;
    }
    changed.push(target);
    if (!check) {
      writeFileSync(file, text);
    }
  }
  return changed;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const check = process.argv.includes('--check');
  const changed = await generateTraceAssets({ check });
  if (check && changed.length > 0) {
    console.error(
      `out of date: ${changed.join(', ')}; run node scripts/generate-trace-assets.mjs`
    );
    process.exit(1);
  }
  for (const target of check ? [] : changed) {
    console.log(`wrote ${target}`);
  }
}
